#!/usr/bin/env python3
"""Export the approved artwork to DevCore's indexed, 24-bit BGR format.

Only size and pixel encoding change. Requires Pillow. Run from any directory:
  python3 make_startup_logo.py path/to/approved-logo.png
"""
from pathlib import Path
import argparse
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 256

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('artwork', type=Path)
    args = parser.parse_args()
    asset_dir = ROOT / 'Assets'
    asset_dir.mkdir(exist_ok=True)
    source = Image.open(args.artwork).convert('RGB')
    source.thumbnail((SIZE, SIZE), Image.Resampling.LANCZOS)
    canvas = Image.new('RGB', (SIZE, SIZE), 'black')
    canvas.paste(source, ((SIZE-source.width)//2, (SIZE-source.height)//2))
    indexed = canvas.quantize(colors=64, method=Image.Quantize.MEDIANCUT,
                              dither=Image.Dither.NONE)
    indexed.save(asset_dir / 'OmidTaheri_256.png', optimize=True)
    pixels = indexed.tobytes()
    palette = indexed.getpalette()
    count = max(pixels) + 1
    colors = []
    for i in range(count):
        r, g, b = palette[i*3:i*3+3]
        colors.append((b << 16) | (g << 8) | r)
    lines = [
        '// Generated by scripts/make_startup_logo.py. Do not edit pixel data.',
        '// Approved Omid Taheri artwork; 8-bit indices, COLOR_24BIT BGR palette.',
        '#ifndef OMID_STARTUP_LOGO_DATA_H', '#define OMID_STARTUP_LOGO_DATA_H',
        '#if !defined(COLOR_24BIT)',
        '#error "The Omid startup palette requires the existing COLOR_24BIT build"',
        '#endif',
        'static constexpr int32_t STARTUP_LOGO_WIDTH = 256;',
        'static constexpr int32_t STARTUP_LOGO_HEIGHT = 256;',
        'static const color_t STARTUP_LOGO_PALETTE[] = {',
        '  ' + ', '.join('0x%08Xu' % c for c in colors), '};',
        'static const uint8_t STARTUP_LOGO_PIXELS[] = {',
    ]
    for start in range(0, len(pixels), 24):
        lines.append('  ' + ', '.join(str(v) for v in pixels[start:start+24]) + ',')
    lines += ['};',
        'static_assert(sizeof(STARTUP_LOGO_PIXELS) == 256u * 256u, "Logo pixel count");',
        '#endif', '']
    (ROOT/'Application/StartupLogoData.h').write_text('\n'.join(lines))
    meta = dict(width=SIZE, height=SIZE, palette_colors=count,
                flash_image_bytes=len(pixels)+count*4,
                source_sha256=hashlib.sha256(args.artwork.read_bytes()).hexdigest(),
                indexed_pixel_sha256=hashlib.sha256(pixels).hexdigest())
    (asset_dir/'logo-export.json').write_text(json.dumps(meta, indent=2)+'\n')
    print(json.dumps(meta))

if __name__ == '__main__':
    main()
